$path = "C:\Users\akoda\Documents\GitHub\my-website\index.html"
$lines = Get-Content -Path $path

# We'll build a new array of lines
$newLines = @()
$i = 0

# 1. ADD RANDOM STUFF TO SIDEBAR
# Find the line with </ul> after Discord link and insert before the closing </div>
while ($i -lt $lines.Count) {
    $newLines += $lines[$i]
    
    # After Contact section's </ul>, before sidebar's </div>
    if ($lines[$i] -match '^\s+<li><a href="#" id="discord-link">Discord</a></li>') {
        # Add the closing </ul>
        $i++
        $newLines += $lines[$i]  # This should be </ul>
        
        # Now add RANDOM STUFF section before the sidebar closes
        $newLines += ''
        $newLines += '                <h3>RANDOM STUFF</h3>'
        $newLines += '                <ul>'
        $newLines += '                    <li><a href="#" id="cool-videos-btn" onclick="toggleVideoPlayer(); return false;">cool videos</a></li>'
        $newLines += '                </ul>'
    }
    # Add Video Player HTML before Discord Modal
    elseif ($lines[$i] -match '^\s+<!-- Discord Modal -->') {
        # Insert video player before this line
        $newLines += ''
        $newLines += '    <!-- Video Player Window (Enhanced) -->'
        $newLines += '    <div id="video-player-window" class="video-player-window" style="display: none;">'
        $newLines += '        <div class="video-player-header">'
        $newLines += '            <span>Cool Videos Player 98</span>'
        $newLines += '            <span class="video-player-close" onclick="closeVideoPlayer()">X</span>'
        $newLines += '        </div>'
        $newLines += '        <div class="video-player-body">'
        $newLines += '            <div class="video-main-area">'
        $newLines += '                <video id="video-element" onclick="togglePlayPause()">'
        $newLines += '                    <source id="video-source" src="" type="video/mp4">'
        $newLines += '                    Your browser does not support the video tag.'
        $newLines += '                </video>'
        $newLines += '                '
        $newLines += '                <div class="video-controls-area">'
        $newLines += '                    <div class="seek-bar-container" id="seek-bar-container">'
        $newLines += '                        <div class="seek-bar-fill" id="seek-bar-fill"></div>'
        $newLines += '                    </div>'
        $newLines += '                    <div class="control-buttons">'
        $newLines += '                        <button class="retro-btn" onclick="previousVideo()" title="Previous">|&lt;</button>'
        $newLines += '                        <button class="retro-btn" onclick="togglePlayPause()" id="play-pause-btn-video" title="Play/Pause">▶</button>'
        $newLines += '                        <button class="retro-btn" onclick="stopVideo()" title="Stop">■</button>'
        $newLines += '                        <button class="retro-btn" onclick="nextVideo()" title="Next">&gt;|</button>'
        $newLines += '                        <div class="time-display" id="video-time-display">00:00 / 00:00</div>'
        $newLines += '                    </div>'
        $newLines += '                </div>'
        $newLines += '            </div>'
        $newLines += '            '
        $newLines += '            <div class="video-playlist" id="video-playlist">'
        $newLines += '                <!-- Playlist items generated by JS -->'
        $newLines += '            </div>'
        $newLines += '        </div>'
        $newLines += '    </div>'
        $newLines += ''
        # Now add the original line (Discord Modal comment)
        $newLines += $lines[$i]
    }
    # Add Video Player JS after the audio player code ends
    elseif ($lines[$i] -match '^\s+\}$' -and $i -gt 0 -and $lines[$i-1] -match 'sessionStorage\.setItem') {
        $newLines += $lines[$i]  # Add the closing brace
        $newLines += ''
        $newLines += '        // Video Player Functionality (Enhanced)'
        $newLines += '        const videoFiles = ['
        $newLines += '            "Authority Zero - Revolution (Official Video).mp4",'
        $newLines += '            "Crysis 3 - Skillet Hero - Music Video - HD - Ray Christian Bustamante (360p, h264).mp4",'
        $newLines += '            "Koto - Jabdah Live Perfromance.mp4",'
        $newLines += '            "Ondrej Matejka - Secret (video-converter.com).mp4",'
        $newLines += '            "Ondrej Matejka - Secret.mp4",'
        $newLines += '            "Quake 4 Music Video - SeptemberSun (144p, h264).mp4",'
        $newLines += '            "RvB Season 8 Warthog Scene Re-Edit.mp4",'
        $newLines += '            "The Hurt Locker Повелители Бури (Ария - Твой день).mp4",'
        $newLines += '            "the russian.mp4",'
        $newLines += '            "ytp/the birth they of justise.mp4",'
        $newLines += '            "♪ GODZILLA THE MUSICAL - Cartoon Parody Song - LHUGUENY (360p, h264).mp4",'
        $newLines += '            "♪ HALO THE MUSICAL - Parody Song Animation - LHUGUENY (360p, h264).mp4",'
        $newLines += '            "♪ PREDATOR THE MUSICAL - Animated Parody - LHUGUENY (360p, h264).mp4",'
        $newLines += '            "♪ PROMETHEUS THE MUSICAL - Animated Parody - LHUGUENY (360p, h264).mp4"'
        $newLines += '        ];'
        $newLines += ''
        $newLines += '        let currentVideoIndex = 0;'
        $newLines += '        const videoElement = document.getElementById("video-element");'
        $newLines += '        const seekBarFill = document.getElementById("seek-bar-fill");'
        $newLines += '        const seekBarContainer = document.getElementById("seek-bar-container");'
        $newLines += '        const timeDisplay = document.getElementById("video-time-display");'
        $newLines += '        const playPauseBtnVideo = document.getElementById("play-pause-btn-video");'
        $newLines += ''
        $newLines += '        function initPlaylist() {'
        $newLines += '            const playlist = document.getElementById("video-playlist");'
        $newLines += '            if (!playlist) return;'
        $newLines += '            playlist.innerHTML = "";'
        $newLines += '            videoFiles.forEach((file, index) => {'
        $newLines += '                const item = document.createElement("div");'
        $newLines += '                item.className = "playlist-item";'
        $newLines += '                if (index === currentVideoIndex) item.classList.add("active");'
        $newLines += '                let displayName = file.split("/").pop().replace(".mp4", "");'
        $newLines += '                if (displayName.length > 28) displayName = displayName.substring(0, 25) + "...";'
        $newLines += '                item.textContent = (index + 1) + ". " + displayName;'
        $newLines += '                item.onclick = () => loadVideo(index);'
        $newLines += '                playlist.appendChild(item);'
        $newLines += '            });'
        $newLines += '        }'
        $newLines += ''
        $newLines += '        function toggleVideoPlayer() {'
        $newLines += '            const videoWindow = document.getElementById("video-player-window");'
        $newLines += '            if (videoWindow.style.display === "none" || !videoWindow.style.display) {'
        $newLines += '                videoWindow.style.display = "flex";'
        $newLines += '                initPlaylist();'
        $newLines += '                if (!videoElement.src || videoElement.src === "") {'
        $newLines += '                    loadVideo(0);'
        $newLines += '                }'
        $newLines += '            } else {'
        $newLines += '                videoWindow.style.display = "none";'
        $newLines += '                if (videoElement) videoElement.pause();'
        $newLines += '            }'
        $newLines += '        }'
        $newLines += ''
        $newLines += '        function closeVideoPlayer() {'
        $newLines += '            const videoWindow = document.getElementById("video-player-window");'
        $newLines += '            if (videoElement) videoElement.pause();'
        $newLines += '            videoWindow.style.display = "none";'
        $newLines += '        }'
        $newLines += ''
        $newLines += '        function loadVideo(index) {'
        $newLines += '            if (index >= 0 && index < videoFiles.length) {'
        $newLines += '                currentVideoIndex = index;'
        $newLines += '                const videoSource = document.getElementById("video-source");'
        $newLines += '                videoSource.src = "images/" + encodeURI(videoFiles[index]);'
        $newLines += '                videoElement.load();'
        $newLines += '                videoElement.play().catch(e => console.log("Auto-play prevented"));'
        $newLines += '                '
        $newLines += '                document.querySelectorAll(".playlist-item").forEach((item, i) => {'
        $newLines += '                    if (i === index) item.classList.add("active");'
        $newLines += '                    else item.classList.remove("active");'
        $newLines += '                });'
        $newLines += '                '
        $newLines += '                updatePlayPauseIcon();'
        $newLines += '            }'
        $newLines += '        }'
        $newLines += ''
        $newLines += '        function togglePlayPause() {'
        $newLines += '            if (!videoElement) return;'
        $newLines += '            if (videoElement.paused) {'
        $newLines += '                videoElement.play();'
        $newLines += '            } else {'
        $newLines += '                videoElement.pause();'
        $newLines += '            }'
        $newLines += '            updatePlayPauseIcon();'
        $newLines += '        }'
        $newLines += ''
        $newLines += '        function stopVideo() {'
        $newLines += '            if (!videoElement) return;'
        $newLines += '            videoElement.pause();'
        $newLines += '            videoElement.currentTime = 0;'
        $newLines += '            updatePlayPauseIcon();'
        $newLines += '        }'
        $newLines += ''
        $newLines += '        function updatePlayPauseIcon() {'
        $newLines += '            if (!playPauseBtnVideo || !videoElement) return;'
        $newLines += '            if (videoElement.paused) {'
        $newLines += '                playPauseBtnVideo.textContent = "▶";'
        $newLines += '            } else {'
        $newLines += '                playPauseBtnVideo.textContent = "⏸";'
        $newLines += '            }'
        $newLines += '        }'
        $newLines += ''
        $newLines += '        function nextVideo() {'
        $newLines += '            currentVideoIndex = (currentVideoIndex + 1) % videoFiles.length;'
        $newLines += '            loadVideo(currentVideoIndex);'
        $newLines += '        }'
        $newLines += ''
        $newLines += '        function previousVideo() {'
        $newLines += '            currentVideoIndex = (currentVideoIndex - 1 + videoFiles.length) % videoFiles.length;'
        $newLines += '            loadVideo(currentVideoIndex);'
        $newLines += '        }'
        $newLines += ''
        $newLines += '        function formatTime(seconds) {'
        $newLines += '            if (isNaN(seconds)) return "00:00";'
        $newLines += '            const m = Math.floor(seconds / 60);'
        $newLines += '            const s = Math.floor(seconds % 60);'
        $newLines += '            return (m < 10 ? "0" + m : m) + ":" + (s < 10 ? "0" + s : s);'
        $newLines += '        }'
        $newLines += ''
        $newLines += '        // Event Listeners for Video'
        $newLines += '        if (videoElement) {'
        $newLines += '            videoElement.addEventListener("timeupdate", () => {'
        $newLines += '                if (!videoElement.duration) return;'
        $newLines += '                const percent = (videoElement.currentTime / videoElement.duration) * 100;'
        $newLines += '                if (seekBarFill) seekBarFill.style.width = percent + "%";'
        $newLines += '                if (timeDisplay) {'
        $newLines += '                    timeDisplay.textContent = formatTime(videoElement.currentTime) + " / " + formatTime(videoElement.duration);'
        $newLines += '                }'
        $newLines += '            });'
        $newLines += ''
        $newLines += '            videoElement.addEventListener("ended", nextVideo);'
        $newLines += '            videoElement.addEventListener("play", updatePlayPauseIcon);'
        $newLines += '            videoElement.addEventListener("pause", updatePlayPauseIcon);'
        $newLines += '        }'
        $newLines += ''
        $newLines += '        if (seekBarContainer) {'
        $newLines += '            seekBarContainer.addEventListener("click", (e) => {'
        $newLines += '                if (!videoElement || !videoElement.duration) return;'
        $newLines += '                const rect = seekBarContainer.getBoundingClientRect();'
        $newLines += '                const x = e.clientX - rect.left;'
        $newLines += '                const width = rect.width;'
        $newLines += '                const percent = x / width;'
        $newLines += '                videoElement.currentTime = percent * videoElement.duration;'
        $newLines += '            });'
        $newLines += '        }'
        $newLines += ''
        $newLines += '        // Make Video Player Draggable'
        $newLines += '        const videoPlayerWindow = document.getElementById("video-player-window");'
        $newLines += '        const videoPlayerHeader = document.querySelector(".video-player-header");'
        $newLines += ''
        $newLines += '        if (videoPlayerWindow && videoPlayerHeader) {'
        $newLines += '            let isDraggingVideo = false;'
        $newLines += '            let currentVideoX;'
        $newLines += '            let currentVideoY;'
        $newLines += '            let initialVideoX;'
        $newLines += '            let initialVideoY;'
        $newLines += '            let xVideoOffset = 0;'
        $newLines += '            let yVideoOffset = 0;'
        $newLines += ''
        $newLines += '            videoPlayerHeader.addEventListener("mousedown", dragVideoStart);'
        $newLines += '            document.addEventListener("mousemove", dragVideo);'
        $newLines += '            document.addEventListener("mouseup", dragVideoEnd);'
        $newLines += ''
        $newLines += '            function dragVideoStart(e) {'
        $newLines += '                if (e.target.classList.contains("video-player-close")) return;'
        $newLines += '                initialVideoX = e.clientX - xVideoOffset;'
        $newLines += '                initialVideoY = e.clientY - yVideoOffset;'
        $newLines += ''
        $newLines += '                if (e.target === videoPlayerHeader || videoPlayerHeader.contains(e.target)) {'
        $newLines += '                    isDraggingVideo = true;'
        $newLines += '                    videoPlayerHeader.style.cursor = "grabbing";'
        $newLines += '                }'
        $newLines += '            }'
        $newLines += ''
        $newLines += '            function dragVideo(e) {'
        $newLines += '                if (isDraggingVideo) {'
        $newLines += '                    e.preventDefault();'
        $newLines += '                    currentVideoX = e.clientX - initialVideoX;'
        $newLines += '                    currentVideoY = e.clientY - initialVideoY;'
        $newLines += '                    xVideoOffset = currentVideoX;'
        $newLines += '                    yVideoOffset = currentVideoY;'
        $newLines += '                    videoPlayerWindow.style.transform = "translate(" + currentVideoX + "px, " + currentVideoY + "px)";'
        $newLines += '                }'
        $newLines += '            }'
        $newLines += ''
        $newLines += '            function dragVideoEnd(e) {'
        $newLines += '                initialVideoX = currentVideoX;'
        $newLines += '                initialVideoY = currentVideoY;'
        $newLines += '                isDraggingVideo = false;'
        $newLines += '                videoPlayerHeader.style.cursor = "grab";'
        $newLines += '            }'
        $newLines += ''
        $newLines += '            videoPlayerHeader.style.cursor = "grab";'
        $newLines += '        }'
        # Skip the next line increment since we already added the closing brace
        $i++
        continue
    }
    
    $i++
}

# Write the new file
$newLines | Set-Content -Path $path

Write-Host "Successfully added RANDOM STUFF section and Enhanced Video Player!" -ForegroundColor Green
